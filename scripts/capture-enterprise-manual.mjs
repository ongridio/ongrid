// Capture actual operating states in an isolated browser context.
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require('../web/node_modules/playwright');
const output = resolve('output/enterprise-manual/screenshots');
mkdirSync(output, { recursive: true });
const baseURL = process.env.E2E_BASE_URL || 'http://192.168.1.11:18860';
const browser = await chromium.launch({ channel: 'chrome' });
const manifest = [];
try {
  const context = await browser.newContext({ baseURL, viewport: { width: 1280, height: 1000 }, deviceScaleFactor: 2 });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const shot = async (name, locator = page.locator('.ex-content')) => {
    await locator.waitFor({ state: 'visible' });
    await page.locator('body').ariaSnapshot();
    await locator.screenshot({ path: resolve(output, `${name}.png`), animations: 'disabled' });
    manifest.push({ name, url: page.url(), capturedAt: new Date().toISOString() });
  };
  const go = async path => {
    await page.goto(path);
    await page.locator('.ex-content h1').waitFor();
  };
  const choose = async (label, value) => {
    await page.getByRole('combobox', { name: label, exact: true }).click();
    await page.getByRole('option', { name: value, exact: true }).click();
  };
  const dialog = () => page.getByRole('dialog');
  await page.goto('/');
  await shot('login', page.locator('.ex-login-fields'));
  await page.getByLabel('账号', {exact:true}).fill('   ');
  await page.getByLabel('密码', {exact:true}).fill('local-input-only');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('alert').waitFor();
  await shot('login-error', page.locator('.ex-login-fields'));
  await page.getByLabel('账号', {exact:true}).fill('operator');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('heading', { name: '运维总览', exact: true }).waitFor();
  await shot('overview');
  await page.screenshot({path:resolve(output,'workspace.png'),animations:'disabled',fullPage:true});
  manifest.push({name:'workspace',url:page.url(),capturedAt:new Date().toISOString()});
  await go('/monitoring/overview');
  await shot('monitor-overview');
  for (const category of ['hosts','applications','databases','network','clusters','availability']) {
    await go(`/monitoring/${category}`);
    await choose('健康状态', '需要关注');
    await shot(`monitor-${category}`);
    await page.getByRole('button', {name:'查看详情',exact:true}).first().click();
    await dialog().waitFor();
    await choose('时间范围', '近 6 小时');
    await shot(`monitor-${category}-detail`, dialog());
  }
  await go('/monitoring/hosts');
  await page.getByRole('searchbox', {name:'搜索监控对象'}).fill('not-found-xyz');
  await shot('monitor-empty');
  await page.getByRole('button',{name:'清除筛选',exact:true}).click();
  await page.getByRole('button',{name:'查看详情',exact:true}).first().waitFor();
  await go('/monitoring/logs');
  await page.getByRole('searchbox', {name:'搜索日志'}).fill('上游请求超时');
  await choose('日志级别','ERROR');
  await shot('monitor-logs');
  await page.getByRole('button',{name:'查看详情',exact:true}).first().click();
  await shot('monitor-logs-detail',dialog());
  await go('/monitoring/rules');
  await shot('monitor-rules');
  await page.getByRole('button',{name:'编辑阈值',exact:true}).first().click();
  await page.getByLabel('阈值',{exact:true}).fill('88');
  await shot('monitor-rules-edit',dialog());
  await page.getByRole('button',{name:'保存规则',exact:true}).click();
  await page.reload();
  await page.getByRole('cell',{name:'CPU > 88 %',exact:true}).waitFor();
  await shot('monitor-rules-saved');
  await go('/inventory');
  await page.getByRole('searchbox',{name:'搜索资源'}).fill('order-api-01');
  await shot('assets');
  await page.getByRole('link',{name:'查看详情',exact:true}).click();
  await shot('asset-detail');
  await page.getByRole('link',{name:'查看指标监测',exact:false}).click();
  await shot('metrics');
  await choose('时间范围','近 6 小时');
  await shot('metrics-6h');
  await go('/risk');
  await page.getByRole('searchbox',{name:'搜索告警'}).fill('INC-1201');
  await shot('incidents');
  await page.getByRole('link',{name:'查看详情',exact:true}).click();
  await shot('incident');
  await page.getByRole('button',{name:'确认告警',exact:true}).click();
  await shot('incident-acknowledged');
  await page.getByRole('button',{name:'关闭告警',exact:true}).click();
  await shot('incident-close-confirm',page.getByRole('dialog'));
  await page.getByRole('dialog').getByRole('button',{name:'确认',exact:true}).click();
  await shot('incident-closed');
  await go('/intelligence');
  await page.getByRole('button',{name:'高 CPU 应急排查',exact:true}).click();
  await shot('assistant');
  await page.getByLabel('你的运维问题',{exact:true}).fill('订单服务 CPU 为什么升高？');
  await page.getByRole('button',{name:'发送问题',exact:true}).click();
  await shot('assistant-question');
  await go('/automation?flow=cpu');
  await shot('automation');
  await page.getByRole('button',{name:'模拟执行',exact:true}).nth(1).click();
  await shot('automation-confirm',page.getByRole('dialog'));
  await page.getByRole('dialog').getByRole('button',{name:'确认',exact:true}).click();
  await page.getByRole('status').filter({hasText:'模拟完成'}).waitFor();
  await shot('automation-completed');
  await go('/executions');
  await shot('executions');
  await page.reload();
  await page.locator('.ex-content h1').waitFor();
  await shot('executions-persisted');
  await go('/library');
  await page.getByRole('searchbox',{name:'搜索知识'}).fill('CPU');
  await shot('knowledge-list');
  await go('/library/kb-1');
  await shot('knowledge');
  await page.getByRole('button',{name:'编辑文档',exact:true}).click();
  await shot('knowledge-edit');
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await go('/library/new');
  await page.getByLabel('文档标题',{exact:true}).fill('主机高负载巡检记录');
  await page.getByLabel('正文',{exact:true}).fill('一、检查对象\norder-api-01，commerce 业务域。\n\n二、检查内容\n核对 CPU、内存与关联告警，查看近 6 小时趋势。\n\n三、核验记录\n记录异常指标、检查时间和后续处理建议。');
  await shot('knowledge-new');
  await page.getByRole('button',{name:'保存文档',exact:true}).click();
  await page.getByRole('heading',{name:'主机高负载巡检记录',exact:true}).waitFor();
  await shot('knowledge-saved');
  await go('/overview');
  await page.getByRole('button',{name:'账户菜单',exact:true}).click();
  await shot('account',page.getByRole('menu'));
  await page.getByRole('menuitem',{name:'恢复示例数据',exact:true}).click();
  await shot('account-reset',page.getByRole('dialog'));
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click();
  await go('/about');
  await shot('about');
  if (errors.length) throw new Error(errors.join('\n'));
  writeFileSync(resolve(output,'manifest.json'), JSON.stringify({baseURL,captures:manifest},null,2));
  console.log(`Captured ${manifest.length} operating states in ${output}`);
} finally { await browser.close(); }
