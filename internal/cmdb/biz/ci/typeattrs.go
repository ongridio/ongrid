// AttributeSet is a CI type's effective attribute definitions, in the form the
// value planner needs: one spec per attribute, plus the lookups a request uses
// to name an attribute.
//
// It is produced by the MODEL side, not here. A CI type's attribute set spans
// its whole inheritance chain and is derived from the binding rows, which is
// the model-configuration module's job; duplicating that walk here would be a
// second implementation of the one rule the two modules must agree on exactly.
type AttributeSet struct {
	// Type is the CI type itself.
	Type citypemodel.CIType

	// Specs is keyed by attribute id. The map includes inherited attributes,
	// with the model's own binding overriding an ancestor's where both exist.
	Specs map[model.ID]AttributeSpec

	// ByName and ByAlias resolve a request's field reference to an attribute.
	// cantor accepted either, and a duplicate name or alias across the chain is
	// resolved the same way the effective set is: the first declaration in
	// chain order wins.
	ByName  map[string]model.ID
	ByAlias map[string]model.ID

	// UniqueAttrID identifies an instance of this type. Every create needs it.
	UniqueAttrID model.ID

	// UniqueAttr is the spec of the unique attribute, for the small amount of
	// per-attribute behaviour a create needs — whether it is multi-valued,
	// whether its default generates the value.
	UniqueAttr AttributeSpec

	// ShowAttr is the spec of the attribute that LABELS an instance: cantor's
	// `show_id`, falling back to the unique attribute when the model declares
	// none. It is what a tree node's title is, so it is resolved here rather
	// than re-derived by each reader — `show_id or unique_id` is one rule and
	// it should have one implementation.
	//
	// It is ZERO when the model declares neither, which is a model cantor would
	// have crashed rendering; the readers fall back to the instance id.
	ShowAttr AttributeSpec

	// UniqueDefault is cantor's default token for the unique attribute, if it
	// has one. See DefaultToken.
	UniqueDefault DefaultToken
}

// DefaultToken is one of cantor's computed default tokens.
//
// The attribute's `default` column holds either a literal or one of these,
// told apart by the envelope being exactly `{"default": "<token>"}`. They are
// enumerated rather than parsed on use because each one is generated by a
// different mechanism and only two of them are implemented.
type DefaultToken string

const (
	// DefaultNone means the stored default is a literal value, not a token.
	DefaultNone DefaultToken = ""

	// DefaultCreatedAt is `$created_at`: the write's timestamp.
	DefaultCreatedAt DefaultToken = "$created_at"

	// DefaultUpdatedAt is `$updated_at`: the write's timestamp.
	DefaultUpdatedAt DefaultToken = "$updated_at"

	// DefaultAutoIncID is `$auto_inc_id`: a per-attribute counter.
	//
	// THE PORT DOES NOT IMPLEMENT IT. cantor generated it from a Redis counter
	// and the port has neither Redis nor a counter table, so an attribute whose
	// default is this token cannot be created. Reporting that is the honest
	// outcome: silently leaving the unique value empty would make every
	// instance of the model collide on the empty string.
	DefaultAutoIncID DefaultToken = "$auto_inc_id"
)

// ClassifyDefault reports whether a stored default is one of cantor's tokens.
func ClassifyDefault(stored map[string]any) (DefaultToken, any, bool) {
	if len(stored) == 0 {
		return DefaultNone, nil, false
	}
	raw, ok := stored["default"]
	if !ok {
		return DefaultNone, nil, false
	}
	if s, ok := raw.(string); ok {
		switch DefaultToken(s) {
		case DefaultCreatedAt, DefaultUpdatedAt, DefaultAutoIncID:
			return DefaultToken(s), nil, true
		}
	}
	return DefaultNone, raw, true
}

// ErrAutoIncIDUnsupported is returned when a model's unique attribute derives
// its value from cantor's counter.
var ErrAutoIncIDUnsupported = fmt.Errorf(
	"%w: this model's identifier is generated by a counter the port does not have", errs.ErrNotWiredYet)

// TypeResolver is the model side of the instance layer: what a model's
// attributes are, and where its hierarchy goes.
//
// It is declared here, in the consumer, because that is the port's convention
// and because it keeps the direction of the dependency honest: instances need
// model definitions, and model definitions need nothing from instances.
//
// THE TWO HALVES ARE ONE PORT because one object answers both. The model
// configuration use case resolves a model's effective attribute set AND holds
// the relation graph; splitting them would add a second injection point wired
// to the same value, which is a cost with no separation behind it.
type TypeResolver interface {
	// ResolveForCI resolves a type by numeric id or exact name and returns its
	// effective attribute set. It returns (nil, nil) when nothing matches, so
	// the caller owns the not-found reporting.
	ResolveForCI(ctx context.Context, ref string) (*AttributeSet, error)

	// RelationBetween returns the rule a model pair declares, or ok=false when
	// the models may not be related at all.
	RelationBetween(ctx context.Context, parentTypeID, childTypeID model.ID) (TypeRelationRule, bool, error)

	// HierarchyLevels describes the model graph below (or, reversed, above) a
	// model, for the levels a hierarchy walk passes through.
	HierarchyLevels(ctx context.Context, rootTypeID model.ID, maxLevel int, reverse bool) (HierarchyLevels, error)
}

// TypeRelationRule is one model pair's declared relation.
type TypeRelationRule struct {
	// RelationTypeID is the relation type a new edge between the pair takes
	// when the caller does not name one.
	RelationTypeID model.ID

	// Constraint is the cardinality rule the write path enforces.
	Constraint model.Constraint

	// RelationTypeName is that relation type's vocabulary word, which the path
	// search labels its edges with. Empty when the relation type row is gone,
	// which is why it is a name rather than a second id the caller has to
	// resolve somewhere else.
	RelationTypeName string
}

// HierarchyLevels is the model graph a hierarchy walk needs.
type HierarchyLevels struct {
	// TypesAtLevel holds the models exactly N hops from the root, keyed by
	// level, counting from 1. It exists to reproduce the type scope cantor
	// synthesised into the CI query: an instance the walk reaches through an
	// edge whose model rule has since been removed is EXCLUDED, because the
	// graph no longer says that model belongs at that level.
	TypesAtLevel map[int][]model.ID

	// ManyToManyLevels are the levels whose walk is scoped by the ancestor
	// path, because the model graph marks them many-to-many.
	ManyToManyLevels []int
}

// ResolveAttrID resolves a request's field reference against the set.
//
// THREE FORMS ARE ACCEPTED, in cantor's order: a numeric id, then the name,
// then the alias. The order matters when a model has an attribute literally
// named "2024" — addressing it by name still works, because the id lookup fails
// first and falls through.
func (s *AttributeSet) ResolveAttrID(ref string) (model.ID, bool) {
	ref = strings.TrimSpace(ref)
	if ref == "" {
		return 0, false
	}
	if id, ok := parseID(ref); ok {
		if _, exists := s.Specs[id]; exists {
			return id, true
		}
	}
	if id, ok := s.ByName[ref]; ok {
		return id, true
	}
	if id, ok := s.ByAlias[ref]; ok {
		return id, true
	}
	return 0, false
}

// SpecsAttrID resolves one of the model's attribute names to its id, or zero
// when the model does not carry it. It is the "may legitimately be absent" half
// of the built-in vocabulary: the rack's own attributes are required, a device
// model's are not.
func (s *AttributeSet) SpecsAttrID(name string) model.ID {
	id, _ := s.ByName[name]
	return id
}

func parseID(s string) (model.ID, bool) {
	var n int64
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return 0, false
		}
		n = n*10 + int64(s[i]-'0')
		if n > 2147483647 {
			return 0, false
		}
	}
	if n <= 0 {
		return 0, false
	}
	return model.ID(n), true
}
