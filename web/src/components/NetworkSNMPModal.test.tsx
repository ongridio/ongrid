import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { beforeEach, expect, it, vi } from 'vitest';
import { NetworkSNMPModal } from './NetworkSNMPModal';
import * as devices from '@/api/devices';
import * as secrets from '@/api/secrets';
vi.mock('@/api/devices');
vi.mock('@/api/secrets');
const device = { id: 42, name: 'SW-01', ip_address: '192.0.2.10' };
const detail = { device_id: 42, device_kind: 'switch', reachability_status: 'unknown', management_address: '192.0.2.10', scanner_host_device_id: 3, poll_enabled: true, poll_credential_name: 'network-read', poll_interval_seconds: 300, poll_port: 161 };
beforeEach(() => {
  vi.resetAllMocks();
  vi.mocked(devices.listDevices).mockResolvedValue({ items: [{ id: 3, name: 'scanner-a', scope: 'host', current_edge_id: 17, online: true }], total: 1 });
  vi.mocked(secrets.listSecrets).mockResolvedValue({ items: [{ id: 1, name: 'network-read', type: 'snmp', description: '', field_keys: ['community'], created_at: '', updated_at: '' }] });
  vi.mocked(devices.getNetworkDeviceDetail).mockResolvedValue(detail);
  vi.mocked(devices.testNetworkSNMP).mockResolvedValue({ ok: true, sys_name: 'SW-01', interface_count: 24, duration_ms: 10 });
  vi.mocked(devices.configureNetworkPolling).mockResolvedValue(detail);
});
it('tests unsaved settings and saves durable scanner identity, not Edge identity', async () => {
  const saved = vi.fn();
  render(<NetworkSNMPModal device={device} onClose={vi.fn()} onSaved={saved} />);
  const button = await screen.findByRole('button', { name: '测试连接' });
  await waitFor(() => expect(button).toBeEnabled());
  expect(screen.getByRole('button', { name: '保存并启用' })).toBeDisabled();
  fireEvent.click(button);
  await screen.findByText(/测试通过/);
  expect(devices.configureNetworkPolling).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: '保存并启用' }));
  await waitFor(() => expect(saved).toHaveBeenCalled());
  expect(devices.configureNetworkPolling).toHaveBeenCalledWith(42, expect.objectContaining({ scanner_host_device_id: 3, credential_name: 'network-read', address: '192.0.2.10', enabled: true }));
});
it('invalidates the test when address changes and preserves the draft on failure', async () => {
  render(<NetworkSNMPModal device={device} onClose={vi.fn()} onSaved={vi.fn()} />);
  await waitFor(() => expect(screen.getByRole('button', { name: '测试连接' })).toBeEnabled());
  fireEvent.click(screen.getByRole('button', { name: '测试连接' }));
  await screen.findByText(/测试通过/);
  fireEvent.change(screen.getByLabelText('管理地址'), { target: { value: '192.0.2.11' } });
  expect(screen.getByRole('button', { name: '保存并启用' })).toBeDisabled();
  vi.mocked(devices.testNetworkSNMP).mockRejectedValue(new Error('SNMP verification failed'));
  fireEvent.click(screen.getByRole('button', { name: '测试连接' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('SNMP verification failed');
  expect(screen.getByLabelText('管理地址')).toHaveValue('192.0.2.11');
});
it('creates a reusable v2c vault credential without putting the secret in device configuration', async () => {
  const user = userEvent.setup();
  vi.mocked(secrets.createSecret).mockResolvedValue({ id: 2, name: 'new-read', type: 'snmp', description: '', field_keys: ['community'], created_at: '', updated_at: '' });
  render(<NetworkSNMPModal device={device} onClose={vi.fn()} onSaved={vi.fn()} />);
  await waitFor(() => expect(screen.getByRole('button', { name: '测试连接' })).toBeEnabled());
  await user.click(screen.getByRole('combobox', { name: 'SNMP 凭证' }));
  await user.click(await screen.findByRole('option', { name: '＋ 新建凭证' }));
  await user.type(screen.getByLabelText('凭证名称'), 'new-read');
  await user.click(screen.getByRole('combobox', { name: '版本' }));
  await user.click(await screen.findByRole('option', { name: 'SNMP v2c' }));
  await user.type(screen.getByLabelText('Community'), 'private-test');
  await user.click(screen.getByRole('button', { name: '保存凭证' }));
  await waitFor(() => expect(secrets.createSecret).toHaveBeenCalledWith({ name: 'new-read', type: 'snmp', fields: { version: 'v2c', community: 'private-test' } }));
  await user.click(screen.getByRole('button', { name: '测试连接' }));
  await waitFor(() => expect(devices.testNetworkSNMP).toHaveBeenCalledWith(42, false, expect.objectContaining({ credential_name: 'new-read' })));
  expect(JSON.stringify(vi.mocked(devices.testNetworkSNMP).mock.calls)).not.toContain('private-test');
});
it('adds a manually entered address without a discovery candidate or existing device', async () => {
  const user = userEvent.setup(); const saved = vi.fn();
  vi.mocked(devices.testNewNetworkSNMP).mockResolvedValue({ ok: true, sys_name: 'manual-switch', interface_count: 8, duration_ms: 5 });
  vi.mocked(devices.createNetworkSNMP).mockResolvedValue(detail);
  render(<NetworkSNMPModal onClose={vi.fn()} onSaved={saved} />);
  expect(screen.getByRole('dialog')).toHaveTextContent('添加 SNMP 设备');
  await waitFor(() => expect(screen.getByLabelText('管理地址')).toBeEnabled());
  expect(screen.getByLabelText('管理地址')).toHaveValue('');
  await user.type(screen.getByLabelText('管理地址'), '192.0.2.88');
  await user.click(screen.getByRole('combobox', { name: 'SNMP 凭证' }));
  await user.click(await screen.findByRole('option', { name: 'network-read' }));
  expect(screen.getByRole('button', { name: '保存并加入设备' })).toBeDisabled();
  await user.click(screen.getByRole('button', { name: '测试连接' }));
  await screen.findByText(/测试通过/);
  expect(devices.createNetworkSNMP).not.toHaveBeenCalled();
  await user.click(screen.getByRole('button', { name: '保存并加入设备' }));
  await waitFor(() => expect(saved).toHaveBeenCalled());
  expect(devices.createNetworkSNMP).toHaveBeenCalledWith(expect.objectContaining({ address: '192.0.2.88', scanner_host_device_id: 3, credential_name: 'network-read' }));
  expect(devices.getNetworkDeviceDetail).not.toHaveBeenCalled();
  expect(devices.configureCandidateSNMP).not.toHaveBeenCalled();
});
